const SPECIAL = /[.*+?^${}()|[\]\\/]/g;

function termPattern(term: string): string {
  return term
    .split(/[\s-]+/)
    .map((word) => word.replace(SPECIAL, "\\$&").replace(/'/g, "'?"))
    .join("[\\s-]?");
}

// Lookarounds rather than \b so terms that start or end with a symbol ("ci/cd") still get
// whole-word matching, and "health" never fires inside "healthy".
export function termsToRegex(terms: readonly string[]): RegExp {
  return new RegExp(`(?<![a-z0-9])(?:${terms.map(termPattern).join("|")})s?(?![a-z0-9])`);
}
